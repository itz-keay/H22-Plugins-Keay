"""Building blocks shared by the rigging modules (Houdini side).

* :func:`skeleton_sop` turns a list of :class:`core.guides.Joint` into a
  Python SOP + transform-init wrangle, i.e. a valid KineFX skeleton.
* :func:`skin` binds a mesh to rest/animated skeletons (biharmonic,
  proximity or rigid).
* :func:`apex_character` packages mesh + skeleton into an APEX character
  folder and adds a base FK rig with the Autorig Component, when the running
  Houdini has those nodes (best effort, logged otherwise).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence

from .. import compat, network
from ..compat import LOG, require_hou
from ..core import guides

_SKELETON_CODE = '''# Generated by ApexKinefxStudio (rigging/common.py). Rebuild the rig to change it.
import json
node = hou.pwd()
geo = node.geometry()
data = json.loads({payload!r})
attr_types = {{}}
for j in data:
    for k, v in j["attrs"].items():
        if k not in attr_types:
            attr_types[k] = type(v)
geo.addAttrib(hou.attribType.Point, "name", "")
defaults = {{int: 0, bool: 0, float: 0.0, str: ""}}
for k, t in attr_types.items():
    if geo.findPointAttrib(k) is None:
        geo.addAttrib(hou.attribType.Point, k, defaults.get(t, ""))
pts = {{}}
for j in data:
    p = geo.createPoint()
    p.setPosition(j["pos"])
    p.setAttribValue("name", j["name"])
    for k, v in j["attrs"].items():
        t = attr_types[k]
        if t is bool:
            v = int(v)
        elif t is float:
            v = float(v)
        elif t is int:
            v = int(v)
        else:
            v = str(v)
        p.setAttribValue(k, v)
    pts[j["name"]] = p
for j in data:
    if j["parent"]:
        poly = geo.createPolygon(False)
        poly.addVertex(pts[j["parent"]])
        poly.addVertex(pts[j["name"]])
geo.addAttrib(hou.attribType.Global, "aks_template", "")
geo.setGlobalAttribValue("aks_template", {template!r})
'''


def skeleton_sop(parent, name: str, joints: Sequence[guides.Joint], template: str = "custom"):
    """Create a KineFX skeleton from guide joints. Returns the init wrangle."""
    guides.validate(joints)
    payload = json.dumps(guides.to_dicts(joints))
    code = _SKELETON_CODE.format(payload=payload, template=template)
    py = network.python_sop(parent, f"{name}_points", code)
    init = network.wrangle(parent, f"{name}_init_transforms", "skeleton_init", run_over="detail",
                           inputs=[py])
    return init


@dataclass
class SkinResult:
    captured: object
    deformed: object


def skin(parent, mesh, rest_skel, anim_skel, method: str = "biharmonic", name: str = "skin") -> SkinResult:
    """Bind ``mesh`` to the skeleton and deform it.

    method: ``biharmonic`` (smooth, needs a watertight mesh), ``proximity``
    (robust fallback), or ``rigid`` (per-piece, for vehicles and robots; uses
    the prim ``name`` attribute to pick joints).
    """
    if method == "rigid":
        bind = network.wrangle(parent, f"{name}_rigid_bind", "rigid_bind", run_over="points",
                               inputs=[mesh, rest_skel], parms=[
                                   network.ParmSpec("piece_attrib", "Piece Attribute", "string", "name"),
                                   network.ParmSpec("default_joint", "Default Joint", "string", "body"),
                               ])
        deform = network.wrangle(parent, f"{name}_rigid_skin", "rigid_skin", run_over="points",
                                 inputs=[bind, rest_skel, anim_skel])
        return SkinResult(bind, deform)

    key = "joint_capture_biharmonic" if method == "biharmonic" else "joint_capture_proximity"
    capture = compat.create(parent, key, f"{name}_capture", required=False)
    if capture is None and key != "joint_capture_proximity":
        capture = compat.create(parent, "joint_capture_proximity", f"{name}_capture", required=False)
    if capture is None:
        LOG.warning("No joint capture SOP available; falling back to rigid skinning.")
        return skin(parent, mesh, rest_skel, anim_skel, "rigid", name)
    compat.connect_by_label(capture, mesh, ["geometry", "mesh", "rest"], fallback_index=0)
    compat.connect_by_label(capture, rest_skel, ["skeleton", "capture pose", "pose"], fallback_index=1)
    deform = compat.create(parent, "joint_deform", f"{name}_deform")
    deform.setInput(0, capture)
    deform.setInput(1, rest_skel)
    deform.setInput(2, anim_skel)
    return SkinResult(capture, deform)


def outputs(parent, rest_skel, anim_skel, mesh=None, prefix: str = "OUT") -> Dict[str, object]:
    """Standard output nulls used by every builder (and by the HDA wrappers)."""
    outs = {
        "rest": network.null(parent, f"{prefix}_REST_SKELETON", rest_skel, (0.4, 0.8, 0.4)),
        "anim": network.null(parent, f"{prefix}_ANIM_SKELETON", anim_skel, (0.3, 0.6, 1.0)),
    }
    if mesh is not None:
        outs["mesh"] = network.null(parent, f"{prefix}_MESH", mesh, (1.0, 0.8, 0.2))
    return outs


def apex_character(parent, mesh, rest_skel, name: str = "apex", add_fk_rig: bool = True):
    """Package mesh + skeleton as an APEX character folder (best effort).

    Builds ``Pack Folder`` (Base.shp / Base.skel) and, when requested, an
    ``APEX Autorig Component`` set to the FK transform component, which gives
    every joint an animatable control. Returns the last node, or None when the
    APEX nodes are unavailable in this build.
    """
    pack = compat.create(parent, "pack_folder", f"{name}_character", required=False)
    if pack is None:
        LOG.warning("Pack Folder SOP not found; skipping APEX packaging.")
        return None
    pack.setInput(0, mesh)
    pack.setInput(1, rest_skel)
    # Pack Folder names each input; parm names differ between builds.
    compat.set_parm(pack, ("name1", "names1", "name_1"), "Base.shp", warn=False)
    compat.set_parm(pack, ("name2", "names2", "name_2"), "Base.skel", warn=False)
    last = pack
    if add_fk_rig:
        fk = compat.create(parent, "apex_autorig_component", f"{name}_fk_rig", required=False)
        if fk is not None:
            fk.setInput(0, pack)
            compat.set_parm(fk, ("component", "componenttype", "source"), "fktransform", warn=True)
            last = fk
    network.note(parent, "APEX character (best effort). Verify the Pack Folder entry names\n"
                         "(Base.shp / Base.skel) and the Autorig component in your Houdini build.\n"
                         "Then add an APEX Scene Animate node to animate the controls.", near=last)
    return last
